// 把中文场景对象按语言合并成运行时场景
export function localizeScene(scene, lang) {
  if (lang !== 'en' || !scene) return scene;
  const en = SCENE_EN[scene.id];
  if (!en) return scene;
  return {
    ...scene,
    titleCn: en.title || scene.titleCn,
    titleEn: scene.titleCn,
    kicker: en.kicker || scene.kicker,
    desc: en.desc || scene.desc,
    principle: en.principle || scene.principle,
    readoutLabel: en.readoutLabel || scene.readoutLabel,
    clipLegend: en.clipLegend || scene.clipLegend,
    facts: scene.facts.map(([k, v], i) => [en.factKeys?.[i] || k, en.factVals?.[i] || v]),
    stages: scene.stages.map((s, i) => ({ ...s, ...(en.stages?.[i] || {}) })),
    steps: (scene.steps || []).map((s, i) => ({ ...s, ...(en.steps?.[i] || {}) })),
    options: (scene.options || []).map((o, i) => ({ ...o, label: en.options?.[i] || o.label })),
    principleTree: scene.principleTree && en.tree
      ? {
          ...scene.principleTree,
          title: en.tree.title || scene.principleTree.title,
          nodes: scene.principleTree.nodes.map((n, i) => ({ ...n, ...(en.tree.nodes?.[i] || {}) })),
        }
      : scene.principleTree,
  };
}

